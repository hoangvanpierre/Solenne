// ---------------------------------------------------------------------------
// Verified customer reviews (migration 0015).
//
// Every review in this model is a *verified purchase* by construction: the
// database refuses to insert a row unless the author owns a delivered order
// item for the product. That is why there is no `isVerified` field to pass
// around — the review exists, therefore it is verified.
//
// The public model deliberately omits `userId` and `orderItemId`. 0015 grants
// `authenticated` no SELECT on either column, so they are unreachable from the
// storefront and from the author's own surface (which uses the
// `get_my_product_review` RPC instead).
// ---------------------------------------------------------------------------

export type ReviewStatus = "published" | "hidden";

/** Storefront ordering of the loaded review window. */
export type ReviewSort = "newest" | "oldest" | "highest" | "lowest";

export type ReviewReportReason =
  | "spam"
  | "abuse"
  | "harassment"
  | "personal_information"
  | "irrelevant"
  | "other";

export type ReviewReportStatus = "open" | "resolved" | "dismissed";

/** A review as the storefront and the author's own surface may see it. */
export interface ProductReview {
  id: string;
  productId: string;
  /** 1–5, guaranteed by a CHECK constraint and re-validated in the app. */
  rating: number;
  title: string;
  body: string;
  /**
   * Per-review pseudonym generated by the database from the review id
   * (`Solenne Customer #<8 hex>`), or null. Never a profile name.
   */
  displayName: string | null;
  status: ReviewStatus;
  /** Present on the author's own hidden review; null for public rows. */
  hiddenReason: string | null;
  createdAt: string;
  updatedAt: string;
}

/**
 * Exact row returned by `public.get_my_product_review(p_product_id uuid)`.
 *
 * The RPC is the only way an author can read their own review: `authenticated`
 * has no `user_id` SELECT grant, and the function returns no author id or
 * purchase evidence. `numeric`/`smallint` arrive as numbers, but PostgREST can
 * serialize them as strings, so the mapper normalizes both.
 */
export interface OwnProductReviewRow {
  id: string;
  product_id: string;
  rating: number | string;
  title: string;
  body: string;
  display_name: string | null;
  status: string;
  hidden_reason: string | null;
  created_at: string;
  updated_at: string;
}

export type ReviewDistribution = Record<1 | 2 | 3 | 4 | 5, number>;

export interface ReviewSummary {
  productId: string;
  reviewCount: number;
  /** Rounded to two decimals, or null when there is nothing to average. */
  averageRating: number | null;
  distribution: ReviewDistribution;
}

/**
 * Whether the current customer may write or edit a review for a product.
 * `hasDeliveredPurchase` is derived from `orders` + `order_items` on the
 * server; `hasReview` from the caller's own row.
 */
export interface ReviewEligibility {
  hasDeliveredPurchase: boolean;
  hasReview: boolean;
  canWrite: boolean;
  canEdit: boolean;
}

/**
 * A delivered product the customer could review (or has already reviewed).
 * Backs the "awaiting your review" list on /account/orders.
 */
export interface ReviewableItem {
  productId: string;
  productName: string;
  productSlug: string | null;
  orderId: string;
  orderNumber: string;
  orderCreatedAt: string;
  /** Existing review id, or null when the piece has not been reviewed yet. */
  reviewId: string | null;
}

export interface ReviewReport {
  id: string;
  reviewId: string;
  /**
   * The reporter's identity is deliberately not carried here: the moderation
   * queue only needs the complaint, and a profile UUID is an internal id that
   * has no business leaving the database.
   */
  reason: ReviewReportReason;
  details: string | null;
  status: ReviewReportStatus;
  resolutionNote: string | null;
  createdAt: string;
  updatedAt: string;
}

/** The review a report points at, as the moderation queue renders it. */
export interface ReportedReview {
  id: string;
  productId: string;
  productName: string;
  productSlug: string | null;
  rating: number;
  title: string;
  body: string;
  displayName: string | null;
  status: ReviewStatus;
  createdAt: string;
}

/** One row of the moderation queue: a report plus the review it targets. */
export interface AdminReviewReportEntry {
  report: ReviewReport;
  review: ReportedReview | null;
}

// ---------------------------------------------------------------------------
// Back-office "All Reviews" browsing (read-only monitoring).
//
// This surface is deliberately separate from the report queue: it lists the
// review table itself, and it carries no author UUID, purchase evidence or
// moderation actor. `displayName` is the database-generated pseudonym, and
// `hiddenReason` is not read at all — the column exists on the row, but
// monitoring does not need it.
// ---------------------------------------------------------------------------

/** Top-level view of /admin/reviews. */
export type AdminReviewView = "all" | "reports";

/** Publication-status filter of the All Reviews view. */
export type AdminReviewStatusFilter = "all" | "published" | "hidden";

/** One row of the All Reviews table, joined to its product for display. */
export interface AdminReviewEntry {
  id: string;
  productId: string;
  /** Empty string when the product row could not be resolved. */
  productName: string;
  productSlug: string | null;
  /** 1–5, normalized from the `smallint` column. */
  rating: number;
  title: string;
  body: string;
  /** Per-review pseudonym from the database; never a profile name. */
  displayName: string | null;
  status: ReviewStatus;
  createdAt: string;
  updatedAt: string;
}

/** One page of the All Reviews list. */
export interface AdminReviewQueryResult {
  reviews: AdminReviewEntry[];
  /** Exact number of rows matching the active filters. */
  totalCount: number;
  page: number;
  limit: number;
  hasMore: boolean;
}

/**
 * Unfiltered publication totals for the page header. `total` is the sum of the
 * two states, which is exact because `product_reviews.status` is constrained to
 * `published`/`hidden` and nothing else can exist.
 */
export interface AdminReviewStatusCounts {
  total: number;
  published: number;
  hidden: number;
}

/** Product option for the All Reviews product filter. */
export interface AdminReviewProductOption {
  id: string;
  name: string;
  slug: string | null;
}

/** Everything the product-detail reviews section needs in one round trip. */
export interface ProductReviewsPageData {
  /** False when the review schema/query is unavailable; the UI degrades. */
  available: boolean;
  reviews: ProductReview[];
  summary: ReviewSummary;
  ownReview: ProductReview | null;
  eligibility: ReviewEligibility;
  isAuthenticated: boolean;
}
